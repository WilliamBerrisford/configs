#!/usr/bin/env bash
# Regenerate vars/packages.yml from the explicitly installed native packages on this system.
set -euo pipefail
cd "$(dirname "$0")"
{
  echo "---"
  echo "# Generated by update-packages.sh from 'pacman -Qqen'"
  echo "pacman_packages:"
  pacman -Qqen | sed 's/^/  - /'
} > vars/packages.yml
